function vertebraName(code) {
  var r = code[0], n = +code.slice(1);
  var kind = { C: "العنقية", T: "الصدرية", L: "القطنية" }[r];
  return "الفقرة " + kind + " " + ordinal(n);
}
/* Roots that leave the spine at this vertebra. Neck roots leave ABOVE their vertebra; the rest leave BELOW. */
function rootsAtVertebra(code) {
  var r = code[0], n = +code.slice(1);
  if (r === "C") return n === 7 ? ["C7", "C8"] : [code];
  return [code];
}

/* For a disc between two vertebrae: which root a herniation usually presses on, by direction. */
function discRoots(upper, lower) {
  var r = upper[0], n = +upper.slice(1);
  var next = lower === "S1" ? "S1" : lower;
  if (r === "C") { // neck: the root that exits at this level is the one below the upper vertebra's number
    var root = "C" + (n + 1);
    return { central: "النخاع الشوكي", paracentral: root, foraminal: root, extraforaminal: root };
  }
  if (r === "T") return { central: "النخاع الشوكي", paracentral: "T" + n, foraminal: "T" + n, extraforaminal: "T" + n };
  // lumbar: back-and-side (paracentral) hits the root travelling down to the next level;
  // in or beyond the foramen it hits the root exiting at this level.
  return { central: "ذيل الفرس", paracentral: next, foraminal: upper, extraforaminal: upper };
}

