function rootInfo(code) {
  if (ROOTS[code]) return ROOTS[code];
  if (code[0] === "T") { // fill thoracic gaps with the nearest described band
    var n = +code.slice(1), keys = [2, 4, 6, 10, 12], best = keys[0];
    keys.forEach(function (k) { if (Math.abs(k - n) < Math.abs(best - n)) best = k; });
    return { feel: "حزام من الجلد حول الصدر أو البطن عند مستواها تقريباً.", move: ROOTS["T" + best].move };
  }
  return { feel: "منطقة السرج.", move: "التحكم في المثانة والأمعاء." };
}

